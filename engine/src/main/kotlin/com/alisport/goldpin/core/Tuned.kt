package com.alisport.goldpin.core

// ═══════════════════════════════════════════════════════════════════════════════
//  پارامترهای «تنظیم‌شده با داده» (Tuned) — جای پیش‌فرض‌های کاغذی سند، وقتی پای
//  کارمزد واقعی در میان است.
//
//  نسخهٔ ۶ (۱٫۴٫۵۱) — مدیریت معاملهٔ باز: «برنده را شب نگه دار»
//  ─────────────────────────────────────────────────────────────────────────────
//  پژوهش ۲۰ساله روی ۲٬۰۳۱ معاملهٔ همین تنظیم (کارمزد ۰٫۷) نشان داد میانگین MFE هر معامله
//  ۱٫۳۸R است ولی آنچه ثبت می‌شد ۰٫۰۰R؛ یعنی سودِ در حال رشد همان روز بسته می‌شد.
//  قاعدهٔ برگزیده: رأس ۲۰:۰۰ UTC فقط **بازنده‌ها** بسته شوند؛ معاملهٔ در سود یک روز دیگر
//  بماند و با تریل کند (روی کلوز ساعتی، از ۳٫۵R با فاصلهٔ ۱٫۵R) محافظت شود. این حالت فقط
//  وقتی روشن می‌شود که نوسان لحظهٔ ورود ≥ ۰٫۳۰٪ قیمت باشد (در بازار کم‌نوسان شب‌ماندن فقط
//  ریسک گپ است). مقایسهٔ شبیه‌سازی روی همان ۲٬۰۳۱ معامله:
//      کلاسیک ‎+۰٫۰۰۳R‎  →  هوشمند ‎+۰٫۰۳۷R‎ به‌ازای هر معامله
//      و در هر چهار دورهٔ پنج‌ساله بهتر: ‎+۰٫۰۰۸‎ / ‎+۰٫۰۱۰‎ / ‎+۰٫۰۵۹‎ / ‎+۰٫۰۵۸R
//  جزئیات و جدول کامل: `docs/GOZARESH-MODIRIYAT-v1.4.51.md`.
//
//  نسخهٔ ۵ (۱٫۴٫۴۹) — پنجرهٔ ساعتی + گیت نوسان (پیش‌فرض ارسالی)
//  ─────────────────────────────────────────────────────────────────────────────
//  گیت نوسان (`minAtrPct = 0.25`): اگر ATR ساختار کمتر از ۰٫۲۵٪ قیمت باشد، ستاپ تازه
//  ساخته نمی‌شود. عددها (کارمزد ۰٫۷):
//      ۱۰ سال: ‎+۰٫۰۰۷R‎ / ‎+۲٬۶۰۵$‎ / افت ۸٬۶۹۳$   →   ‎+۰٫۰۵۹R‎ / ‎+۱۰٬۶۲۹$‎ / افت ۳٬۵۱۶$
//      ۳ سال : ‎+۰٫۰۷۸R‎ / ‎+۹٬۷۵۵$‎            →   ‎+۰٫۱۱۵R‎ / ‎+۹٬۶۸۶$‎ / بدترین ۱۲ ماه ‎−۶۱۷$‎
//      ۲۰ سال: ‎−۰٫۰۱۰R‎ / ‎−۶٬۸۲۳$‎            →   ‎+۰٫۰۰۷R‎ / ‎+۲٬۴۹۶$‎ / افت ۱۰٬۶۶۲$ (مثبت شد)
//  نمودارها: `docs/equity_10y_gate.png` و `docs/equity_20y_gate.png`.
//
//  نسخهٔ ۴ (۱٫۴٫۴۹) — پنجرهٔ ساعتی ورود
//  ─────────────────────────────────────────────────────────────────────────────
//  با ریزش ۲٬۴۱۰ معاملهٔ ده‌ساله و گروه‌بندی بر اساس ساعت UTC، الگوی علّی روشنی پیدا شد:
//  ساعات ۰۰–۰۵ UTC (سشن آسیا) و ۱۵–۲۰ UTC انتظار **منفی** داشتند و ساعات ۰۵–۱۵ UTC
//  (لندن و شروع نیویورک) مثبت. با بستن پنجرهٔ ورود روی ۰۵–۱۵:
//      کل ده سال: ‎−۰٫۰۰۶R‎ / ‎−۴۳۹$‎ / افت ۱۲٬۳۹۷$   →   ‎+۰٫۰۰۷R‎ / ‎+۲٬۶۰۵$‎ / افت ۸٬۶۹۳$
//  یعنی همان خانوادهٔ استراتژی برای اولین بار روی کل دهه مثبت شد، با ۱۸٪ معاملهٔ کمتر.
//  گزارش کامل: `docs/GOZARESH-MANHANI-v1.4.49.md`.
//
//  نسخهٔ ۳ (۱٫۴٫۴۸) — تنظیم روی دادهٔ واقعی **بیست‌ساله** (۶٬۵۶۳٬۷۲۳ کندل M1 طلا،
//  ۲۰۰۶-۰۸-۲۱ تا ۲۰۲۶-۰۸-۲۰، فایل `local-data/goldpin_xauusd_m1_20y.csv.gz` در مخزن)
//  با کارمزد ۰٫۷ دلار. روش: جست‌وجو روی پنجرهٔ آموزش ۲۰۰۶–۲۰۱۶، اعتبارسنجی روی
//  پنجرهٔ نگه‌داشته‌شدهٔ ۲۰۱۷–۲۰۲۶، کنترل جدا روی رژیم اخیر ۲۰۲۳–۲۰۲۶ و عدد نهایی
//  روی کل بیست سال (گزارش: `sweep/` — فازهای ۲۱ تا ۲۶).
//
//  چرا نسخهٔ ۲ (بافر ۹۰۰ تیک) کنار رفت:
//  منحنی بافر روی **هر دو** پنجرهٔ مستقل باز هم صعودی بود: انتظار روی آموزش از
//  ‎−۰٫۰۶۰R‎ (۹۰۰) به ‎−۰٫۰۳۵R‎ (۱۸۰۰) رسید و روی نگه‌داشته‌شده از ‎−۰٫۰۱۵R‎ به
//  ‎−۰٫۰۰۷R‎؛ روی رژیم اخیر هم ۱۸۰۰ برنده بود (‎+۰٫۰۳۳R‎ در برابر ‎+۰٫۰۲۲R‎).
//  پهن‌تر از ۱۸۰۰ (۳۰۰۰/۴۵۰۰) روی آموزش اندکی بهتر ولی روی آزمون و دلار بدتر شد.
//
//  نتیجهٔ اندازه‌گیری‌شدهٔ این نسخه (استراتژی ۱ · Mixed · کارمزد ۰٫۷):
//    کل بیست سال → ۴٬۵۲۴ معامله · نرخ برد ۴۹٫۰٪ · انتظار ‎−۰٫۰۲۰R‎ · خالص ‎−۱۴٬۷۱۵$‎ ·
//                  ضریب سود ۰٫۹۳۷ · بیشترین افت ‎۲۶٬۶۸۲$‎ · ۸۷ ماه مثبت از ۲۴۱
//    کل ده سال   → ۲٬۴۱۰ معامله · انتظار ‎−۰٫۰۰۶R‎ · خالص ‎−۴۳۹$‎ · ضریب سود ۰٫۹۹۷
//    ۲۰۲۳–۲۰۲۶ (رژیم اخیر) → ‎+۰٫۰۳۳R‎ · ‎+۸٬۰۴۶$‎ · ضریب سود ۱٫۱۰۳
//    سال آخر داده (۲۰۲۵-۰۸ تا ۲۰۲۶-۰۸) → ‎+۰٫۰۹۲R‎ · ‎+۷٬۳۷۷$‎ · ضریب سود ۱٫۱۹۸
//  مقایسه: پیش‌فرض سند ۷ روی این داده **صفر سفارش** می‌دهد (فیلتر ۶×۰٫۷=۴٫۲ > سقف ۳).
//
//  ⚠ صادقانه: روی ۲۰۰۶–۲۰۱۶ هیچ ترکیبی از این خانواده سودده نیست (بهترین امید
//  ‎−۰٫۰۱۶R‎ با بافر ۴۵۰۰)؛ لبهٔ این استراتژی با کارمزد ۰٫۷ عمدتاً در رژیم پرنوسانِ
//  سال‌های اخیر وجود دارد. عدد بیست‌ساله هنوز منفی است، ولی کم‌زیان‌ترینِ آزموده‌شده
//  و در رژیم فعلی مثبت. «سود تضمینی» نیست؛ اگر کارمزد کاربر فرق دارد، بخش «تطبیق»
//  در اپ آستانه‌ها را از روی کارمزد او دوباره می‌سازد.
// ═══════════════════════════════════════════════════════════════════════════════

object Tuned {

    /** کارمزد/اسپرد مرجع (واحد قیمت) که این تنظیم با آن آزموده شده است. */
    const val CMSN = 0.7

    /** هدف تریگر ۲ بر حسب R. */
    const val TARGET_R = 7.0

    /** بافر حد ضرر به تیک (× mintick ⇒ ۱۸٫۰۰ دلار فاصلهٔ اضافه از لبهٔ باکس). */
    const val SL_BUF_TICKS = 1800.0

    /** بافر سطح سفارش به تیک؛ منفی یعنی چند تیک **داخل** باکس (پیشنهاد §۴-۳ گزارش ورود). */
    const val ENTRY_BUF_TICKS = -2.0

    /** سقف فاصلهٔ حد ضرر N (§18-31) — باید از فاصلهٔ جدید حد ضرر بزرگ‌تر باشد. */
    const val MAX_SL_UNITS = 80.0

    /** ضریب فیلتر کارمزد §۵-۳: با حد ضرر پهن، خاموش است (خودِ حد ضرر هزینه را پوشش می‌دهد). */
    const val COST_MULT = 0.0

    /** جهت معامله: هم‌جهت با ساختار (معکوس خاموش). در این سال، معکوس منفی بود. */
    const val TRIGGER2_FADE = false

    /**
     * پنجرهٔ ساعتی مجاز ورود تازه (UTC) — نسخهٔ ۴.
     *
     * ۰۵ تا ۱۵ UTC = سشن لندن و شروع نیویورک. بیرون این بازه، معاملات ده‌ساله انتظار
     * منفی داشتند (سشن آسیا و آخر روز). جزئیات و اعداد: گزارش منحنی ۱٫۴٫۴۹.
     */
    const val ENTRY_HOUR_FROM = 5
    const val ENTRY_HOUR_TO = 15

    /**
     * گیت نوسان (نسخهٔ ۵): اگر `ATR(ساختار)/قیمت × ۱۰۰` کمتر از این باشد، ستاپ تازه
     * ساخته نمی‌شود. ۰ = خاموش. عددها: ۱۰ سال ‎+۱۰٬۶۲۹$‎ · ۲۰ سال ‎+۲٬۴۹۶$‎ (هر دو مثبت).
     */
    const val MIN_ATR_PCT = 0.25

    /**
     * مدیریت معاملهٔ باز (نسخهٔ ۷): `1` = هوشمند با دروازهٔ **ثابت** (بهترین اندازه‌گیری ۲۰ساله:
     * ‎+۱۰٬۵۸۳$‎) · `2` = هوشمند با دروازهٔ **تطبیقی-صدکی** (‎+۸٬۶۳۲$‎، خودتنظیم با رژیم) ·
     * `0` = کلاسیک سند §۱۸-۲۷ (‎+۲٬۴۹۶$‎).
     */
    const val MGMT_MODE = 1
    /** آستانهٔ R برای نگه‌داشتن در پایان روز. */
    const val MGMT_HOLD_MIN_R = 0.0
    /** حداکثر روز اضافه (یک شب). */
    const val MGMT_HOLD_DAYS = 1
    /** شروع تریلینگ (R) و فاصلهٔ آن (R). */
    const val MGMT_TRAIL_START_R = 3.5
    const val MGMT_TRAIL_DIST_R = 1.5
    /** دروازهٔ رژیم ثابت: مدیریت هوشمند فقط وقتی ATR/قیمت ≥ این درصد باشد. ۰ = همیشه. */
    const val MGMT_VOL_GATE_PCT = 0.30
    /**
     * دروازهٔ تطبیقی (حالت ۲): آستانه = صدک [MGMT_ADAPT_Q] از نمونه‌های ATR% ساعت‌های اخیر،
     * با پنجرهٔ [MGMT_ADAPT_WINDOW] ساعت (۳۰۰ ≈ ۱۲ روز معاملاتی) و کف [MGMT_ADAPT_FLOOR] درصد.
     * آزمون موتور ۲۰ساله (واقعی، نه شبیه‌سازی): تطبیقی ‎+۰٫۰۲۴۲R‎ · ثابت ‎+۰٫۰۳۱۱R‎ · کلاسیک ‎+۰٫۰۰۶۵R‎.
     * یعنی صدک محلی در بازهٔ ۲۰۱۱–۲۰۱۵ بدتر عمل می‌کند؛ به‌همین‌دلیل پیش‌فرض «ثابت» است.
     */
    const val MGMT_ADAPT_Q = 0.60
    const val MGMT_ADAPT_WINDOW = 300
    const val MGMT_ADAPT_FLOOR = 0.10

    /**
     * اعمال تنظیم آزموده‌شده روی [c]. فقط همان کلیدهایی را عوض می‌کند که در جاروب
     * اثرگذار بودند؛ بقیهٔ تنظیمات کاربر (تایم‌فریم، ریسک، مدیریت مالی…) دست‌نخورده می‌ماند.
     */
    fun apply(c: Settings, cmsn: Double = CMSN) {
        c.trigger2Fade = TRIGGER2_FADE
        c.trigger2TargetR = TARGET_R
        c.slBufTicks = SL_BUF_TICKS
        c.entryBufTicks = ENTRY_BUF_TICKS
        c.maxSlUnits = MAX_SL_UNITS
        c.minSlUnits = 0.0
        c.minSlCostMult = COST_MULT
        // نسخهٔ ۴: پنجرهٔ ساعتی ورود (فیلتر سشن)
        c.entryHourFrom = ENTRY_HOUR_FROM
        c.entryHourTo = ENTRY_HOUR_TO
        // گیت نوسان و هندسهٔ ATR به‌طور پیش‌فرض خاموش‌اند: اندازه‌گیری ده‌ساله نشان داد
        // نسخهٔ ۱٫۵×ATR بدتر از بافر ثابت ۱۸۰۰ است (‎−۰٫۱۳۳R‎ در برابر ‎−۰٫۰۰۶R‎).
        c.minAtrPct = MIN_ATR_PCT
        c.slBufMode = 0
        // نسخهٔ ۶: سیستم مدیریت معاملهٔ باز
        c.mgmtMode = MGMT_MODE
        c.mgmtHoldMinR = MGMT_HOLD_MIN_R
        c.mgmtHoldMaxDays = MGMT_HOLD_DAYS
        c.mgmtTrailStartR = MGMT_TRAIL_START_R
        c.mgmtTrailDistR = MGMT_TRAIL_DIST_R
        c.mgmtVolGatePct = MGMT_VOL_GATE_PCT
        c.maxSlMode = 0
        // [cmsn] صفر یا منفی ⇒ «کارمزد را دست نزن»: هندسهٔ استراتژی تنظیم می‌شود ولی مبنای
        // کارمزد همان می‌ماند که کاربر/بروکر دارد (اسپرد خودکار معقول یا عدد دستی خودش).
        if (cmsn > 0.0) {
            c.cmsnAuto = false
            c.cmsnManual = cmsn
        }
    }

    /**
     * آیا این تنظیمات دقیقاً همان پیش‌فرض‌های دست‌نخوردهٔ سند ۷ (نسخهٔ ۱٫۴٫۳۶ تا ۱٫۴٫۴۱) است؟
     *
     * فقط در این حالت مهاجرت `specRev=9` مقدارها را عوض می‌کند؛ اگر کاربر حتی یکی را
     * دست‌کاری کرده باشد، انتخابش محترم می‌ماند (همان قاعدهٔ مهاجرت‌های قبلی).
     */
    /**
     * آیا این تنظیمات دقیقاً همان خروجی نسخهٔ ۱ این تنظیم است (نسخه‌های ۱٫۴٫۴۲ تا
     * ۱٫۴٫۴۵: هم‌جهت · هدف ۷R · بافر ۲۰۰ · بافر سفارش ‎−۲‎ · N=۱۰ · فیلتر خاموش)؟
     *
     * فقط در این حالت مهاجرت `specRev=10` مقدارها را به نسخهٔ ۲ می‌برد؛ هر انحرافی
     * یعنی کاربر دستی عوض کرده و انتخابش دست‌نخورده می‌ماند.
     */
    fun isUntouchedTunedV1(c: Settings): Boolean =
        !c.trigger2Fade && c.trigger2TargetR == 7.0 && c.minSlCostMult == 0.0 &&
            c.slBufTicks == 200.0 && c.entryBufTicks == -2.0 && c.maxSlUnits == 10.0 &&
            c.minSlUnits == 0.0

    /**
     * آیا این تنظیمات دقیقاً همان خروجی نسخهٔ ۲ این تنظیم است (نسخه‌های ۱٫۴٫۴۶ و
     * ۱٫۴٫۴۷: هم‌جهت · هدف ۷R · بافر ۹۰۰ · بافر سفارش ‎−۲‎ · N=۴۰ · فیلتر خاموش)؟
     *
     * فقط در این حالت مهاجرت `specRev=11` مقدارها را به نسخهٔ ۳ می‌برد؛ هر انحرافی
     * یعنی کاربر دستی عوض کرده و انتخابش دست‌نخورده می‌ماند.
     */
    fun isUntouchedTunedV2(c: Settings): Boolean =
        !c.trigger2Fade && c.trigger2TargetR == 7.0 && c.minSlCostMult == 0.0 &&
            c.slBufTicks == 900.0 && c.entryBufTicks == -2.0 && c.maxSlUnits == 40.0 &&
            c.minSlUnits == 0.0

    /**
     * آیا این تنظیمات دقیقاً همان خروجی نسخهٔ ۳ است (۱٫۴٫۴۸: هم‌جهت · ۷R · بافر ۱۸۰۰ ·
     * N=۸۰ · بافر سفارش ‎−۲‎ · فیلتر خاموش · پنجرهٔ ۱–۲۰)؟
     *
     * فقط در این حالت مهاجرت `specRev=12` پنجرهٔ ساعتی را روی ۰۵–۱۵ می‌گذارد؛ هر انحرافی
     * یعنی کاربر خودش چیزی را عوض کرده و انتخابش محترم می‌ماند.
     */
    fun isUntouchedTunedV3(c: Settings): Boolean =
        !c.trigger2Fade && c.trigger2TargetR == 7.0 && c.minSlCostMult == 0.0 &&
            c.slBufTicks == 1800.0 && c.entryBufTicks == -2.0 && c.maxSlUnits == 80.0 &&
            c.minSlUnits == 0.0 && c.slBufMode == 0 && c.minAtrPct == 0.0 &&
            c.entryHourFrom == 1 && c.entryHourTo == 20

    /**
     * آیا این تنظیمات دقیقاً همان خروجی نسخهٔ ۴ است (۱٫۴٫۴۹: پنجرهٔ ۰۵–۱۵ · گیت نوسان
     * خاموش · هم‌جهت · ۷R · بافر ۱۸۰۰ · N=۸۰)؟ فقط در این حالت مهاجرت `specRev=13`
     * گیت نوسان ۰٫۲۵٪ را روشن می‌کند.
     */
    fun isUntouchedTunedV4(c: Settings): Boolean =
        !c.trigger2Fade && c.trigger2TargetR == 7.0 && c.minSlCostMult == 0.0 &&
            c.slBufTicks == 1800.0 && c.entryBufTicks == -2.0 && c.maxSlUnits == 80.0 &&
            c.minSlUnits == 0.0 && c.slBufMode == 0 && c.minAtrPct == 0.0 &&
            c.entryHourFrom == ENTRY_HOUR_FROM && c.entryHourTo == ENTRY_HOUR_TO

    /**
     * آیا این تنظیمات دقیقاً همان خروجی نسخهٔ ۵ است (۱٫۴٫۴۹: پنجرهٔ ۰۵–۱۵ · گیت نوسان
     * ۰٫۲۵٪ · مدیریت کلاسیک)؟ فقط در این حالت مهاجرت `specRev=14` مدیریت هوشمند را روشن می‌کند.
     */
    fun isUntouchedTunedV5(c: Settings): Boolean =
        !c.trigger2Fade && c.trigger2TargetR == 7.0 && c.minSlCostMult == 0.0 &&
